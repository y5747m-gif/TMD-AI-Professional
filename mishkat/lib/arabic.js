/* ==============================================================
 *  3) التقطيع والتجذيع الخفيف
 * ============================================================== */

const ARABIC_PREFIXES = ["وال", "فال", "بال", "كال", "لل", "ال", "و", "ف", "ب", "ك", "ل"];
const ARABIC_SUFFIXES = ["ات", "ون", "ين", "ها", "هم", "هن", "كم", "كن", "نا", "ه", "ي", "ا"];

function tokenize(text) {
  return normalizeArabic(text)
    .split(/\s+/)
    .filter((t) => t.length >= 2);
}

function stripPrefix(token) {
  for (const p of ARABIC_PREFIXES) {
    if (token.length - p.length >= 3 && token.startsWith(p)) {
      return token.slice(p.length);
    }
  }
  return token;
}

function stripSuffix(token) {
  if (token.length >= 5) {
    for (const s of ARABIC_SUFFIXES) {
      if (token.endsWith(s) && token.length - s.length >= 3) {
        return token.slice(0, token.length - s.length);
      }
    }
  }
  return token;
}

/** جذر خفيف جدًا (أوّل ثلاثة/أربعة أحرف بعد إزالة السوابق واللواحق) */
function lightStem(token) {
  const t = stripSuffix(stripPrefix(token));
  return t.length >= 3 ? t : token;
}

/** كلمات البحث الأساسية بعد إسقاط كلمات التوقف */
function contentTokens(text) {
  const all = tokenize(text);
  const out = [];
  for (const raw of all) {
    const core = stripPrefix(raw);
    if (STOPWORDS.has(raw) && !/^[0-9]+$/.test(raw)) continue;
    if (STOPWORDS.has(core)) continue;
    if (raw.length < 2) continue;
    out.push(raw);
  }
  return out;
}

