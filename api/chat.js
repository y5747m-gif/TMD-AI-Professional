const GROQ_URL =
  "https://api.groq.com/openai/v1/chat/completions";

module.exports = async function handler(req, res) {
  // =========================
  // CORS
  // =========================

  res.setHeader("Cache-Control", "no-store");

  res.setHeader(
    "Access-Control-Allow-Origin",
    "*"
  );

  res.setHeader(
    "Access-Control-Allow-Methods",
    "POST, OPTIONS"
  );

  res.setHeader(
    "Access-Control-Allow-Headers",
    "Content-Type"
  );


  // =========================
  // OPTIONS
  // =========================

  if (req.method === "OPTIONS") {
    return res.status(204).end();
  }


  // =========================
  // POST ONLY
  // =========================

  if (req.method !== "POST") {
    return res.status(405).json({
      ok: false,
      error: "استخدم POST لهذا المسار."
    });
  }


  // =========================
  // GROQ API KEY
  // =========================

  const apiKey =
    process.env.GROQ_API_KEY;

  if (!apiKey) {
    return res.status(500).json({
      ok: false,
      error:
        "GROQ_API_KEY غير موجود في Vercel."
    });
  }


  try {

    // =========================
    // READ REQUEST
    // =========================

    const body =
      typeof req.body === "string"
        ? JSON.parse(req.body || "{}")
        : (req.body || {});


    const messages =
      Array.isArray(body.messages)
        ? body.messages
        : [];


    // =========================
    // CLEAN MESSAGES
    // =========================

    const cleaned =
      messages

        .filter((message) => {

          return (
            message &&
            (
              message.role === "user" ||
              message.role === "assistant"
            ) &&
            typeof message.content === "string"
          );

        })

        .slice(-20)

        .map((message) => {

          return {
            role: message.role,

            content:
              message.content
                .trim()
                .slice(0, 12000)
          };

        })

        .filter(
          (message) =>
            message.content.length > 0
        );


    if (!cleaned.length) {

      return res.status(400).json({
        ok: false,
        error: "اكتب رسالة أولًا."
      });

    }


    // =========================
    // T.M.D AI SYSTEM
    // =========================

    const systemPrompt = `

أنت T.M.D AI، مساعد ذكاء اصطناعي عربي احترافي.

أنت مساعد عام في البرمجة والدراسة والكتابة والبحث والأسئلة العامة، ولديك تخصص إضافي في الدراسات الدينية المقارنة.

==============================
الوضع الديني
==============================

عند سؤال المستخدم عن الدين أو العقيدة أو الكتب المقدسة أو الفتاوى أو الأحكام الشرعية، اتبع القواعد التالية:

1. تعامل باحترام كامل مع جميع الأديان والمذاهب والطوائف.

2. لا تهاجم أو تسخر أو تهين أي دين أو طائفة أو أتباع دين.

3. تستطيع مناقشة الإسلام والمسيحية واليهودية وغيرها من التقاليد الدينية بصورة علمية ومحايدة.

4. تستطيع شرح ومقارنة:
- القرآن الكريم
- كتب الحديث
- كتب الفقه
- كتب التفسير
- الكتاب المقدس
- العهد القديم
- العهد الجديد
- أسفار التوراة
- النصوص اليهودية
- النصوص المسيحية
- وغيرها من المصادر الدينية.

5. لا تدّعِ أن لديك النص الكامل لأي كتاب ديني إذا لم يكن النص متاحًا لك.

6. ممنوع اختلاق:
- آية
- حديث
- نص ديني
- رقم آية
- رقم حديث
- اسم سفر
- رقم إصحاح
- قول عالم
- فتوى
- مرجع أو رابط.

7. إذا طلب المستخدم نصًا حرفيًا من كتاب ديني وأنت غير متأكد من النص، لا تخمّن.

قل بوضوح إنك تحتاج إلى تحديد:
- اسم الكتاب
- اسم السورة أو السفر أو الباب
- رقم الآية أو الحديث أو الإصحاح إن وجد
- الترجمة أو الطبعة عند الحاجة.

8. إذا كان هناك اختلاف بين المذاهب أو الطوائف، اذكر الاختلاف بوضوح.

9. في الفقه الإسلامي:
لا تقدّم نفسك على أنك مفتٍ بشري.

يمكنك:
- شرح الأقوال الفقهية.
- عرض المذاهب.
- ذكر الأدلة المعروفة.
- توضيح موضع الخلاف.
- تقديم معلومات تعليمية.

لكن في المسائل الشخصية أو الخطيرة أو التي يترتب عليها حكم شرعي مهم، أوصِ المستخدم بالرجوع إلى عالم أو مفتٍ موثوق.

10. لا تقل:
"هذه فتوى نهائية مني."

بل استخدم عبارات مثل:
"من الأقوال الفقهية..."
أو:
"بحسب هذا المذهب..."
أو:
"توجد عدة آراء معتبرة..."

11. عند وجود اختلاف ديني، لا تعرض رأيًا واحدًا على أنه حقيقة متفق عليها.

12. إذا سأل المستخدم:
"ما رأي الإسلام في..."
فأجب من منظور المصادر الإسلامية.

وإذا سأل:
"ما رأي المسيحية في..."
فوضّح اختلاف الطوائف المسيحية عند الحاجة.

وإذا سأل:
"ما رأي اليهودية في..."
فوضّح اختلاف التقاليد والمدارس اليهودية عند الحاجة.

13. عند المقارنة بين الأديان:
استخدم جدولًا أو نقاطًا عندما يكون ذلك مفيدًا.

مثال:

الموضوع
- الإسلام
- المسيحية
- اليهودية

ولا تقل إن أحد الأديان صحيح أو خاطئ إلا إذا كان المستخدم يطلب شرح موقف عقيدة معينة، وعندها انسب الحكم إلى تلك العقيدة بدل تقديمه كحقيقة محايدة.

==============================
الدقة في المصادر
==============================

عند ذكر مصدر:

اكتب اسم المصدر بوضوح.

مثال:

المصدر: القرآن الكريم، سورة البقرة.

أو:

المصدر: إنجيل متى، الإصحاح...

لكن لا تخترع رقمًا أو نصًا إذا لم تكن متأكدًا منه.

إذا كان المصدر غير مؤكد، قل:
"أحتاج إلى التحقق من المرجع قبل نسبته إلى المصدر."

==============================
الفتاوى
==============================

إذا كتب المستخدم:
"أعطني فتوى"

فلا تدّعي أنك مفتي.

قل إنك تستطيع تقديم:
- شرح فقهي.
- عرض آراء العلماء.
- مقارنة المذاهب.
- شرح الأدلة.
- توضيح مواضع الاتفاق والاختلاف.

وفي الحالات المهمة شجّع على الرجوع إلى مختص ديني موثوق.

==============================
الأسئلة الحساسة
==============================

إذا كان السؤال متعلقًا بالعنف أو الكراهية ضد جماعة دينية:

لا تشجع الكراهية أو العنف.

يمكنك شرح الخلفية التاريخية أو الدينية بصورة تعليمية ومحايدة.

==============================
اللغة
==============================

استخدم العربية افتراضيًا.

إذا كتب المستخدم بالإنجليزية، أجب بالإنجليزية.

يمكنك استخدام المصطلحات العربية والإنجليزية عند الحاجة.

==============================
أسلوب الإجابة
==============================

ابدأ بالإجابة مباشرة.

لا تطل بدون داعٍ.

استخدم العناوين والنقاط.

إذا كان السؤال دينيًا:

1. الإجابة المختصرة.
2. المصدر أو المصادر إن كانت مؤكدة.
3. شرح المعنى.
4. الخلاف إن وجد.
5. تنبيه عند الحاجة إلى عالم أو مختص.

الأهم:

الدقة قبل السرعة.

لا تخترع مصادر.

لا تخترع نصوصًا دينية.

لا تقدّم تخمينًا على أنه فتوى أو حقيقة دينية.

`;


    // =========================
    // MODEL
    // =========================

    const model =
      process.env.GROQ_MODEL ||
      "openai/gpt-oss-120b";


    // =========================
    // GROQ REQUEST
    // =========================

    const response =
      await fetch(
        GROQ_URL,
        {
          method: "POST",

          headers: {
            "Content-Type":
              "application/json",

            Authorization:
              `Bearer ${apiKey}`
          },

          body: JSON.stringify({

            model,

            messages: [
              {
                role: "system",
                content: systemPrompt
              },

              ...cleaned
            ],

            temperature: 0.2,

            max_completion_tokens: 2000

          })
        }
      );


    // =========================
    // READ RESPONSE
    // =========================

    const data =
      await response
        .json()
        .catch(() => ({}));


    // =========================
    // GROQ ERROR
    // =========================

    if (!response.ok) {

      const message =
        data &&
        data.error &&
        data.error.message
          ? data.error.message
          : `Groq returned HTTP ${response.status}`;


      console.error(
        "Groq API error:",
        data
      );


      return res.status(502).json({
        ok: false,
        error: message
      });

    }


    // =========================
    // EXTRACT ANSWER
    // =========================

    const text =
      data &&
      data.choices &&
      data.choices[0] &&
      data.choices[0].message &&
      typeof data.choices[0].message.content ===
        "string"

        ? data.choices[0]
            .message
            .content
            .trim()

        : "";


    // =========================
    // EMPTY RESPONSE
    // =========================

    if (!text) {

      console.error(
        "Empty Groq response:",
        data
      );


      return res.status(502).json({
        ok: false,
        error:
          "لم تُرجع خدمة Groq نصًا."
      });

    }


    // =========================
    // SUCCESS
    // =========================

    return res.status(200).json({

      ok: true,

      message: text,

      model

    });


  } catch (error) {

    console.error(
      "TMD AI / Groq error:",
      error
    );


    return res.status(500).json({

      ok: false,

      error:
        "حدث خطأ داخلي في الخادم."

    });

  }
};
