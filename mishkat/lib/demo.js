/** يضيف البيانات التجريبية إلى القاعدة */
function seedDemo(store) {
  let videos = 0;
  let chunks = 0;
  for (const v of DEMO_VIDEOS) {
    const segments = segmentsFromText(v.text);
    store.upsertVideo({
      id: v.id,
      title: v.title,
      description: v.description,
      publishedAt: v.publishedAt,
      durationS: v.durationS,
      views: v.views,
      url: `https://www.youtube.com/channel/UCv0g_v1C6JcZALvrkDu98AQ`,
      thumbnail: "",
      sourceKind: "demo",
      hasTranscript: true,
      transcriptLang: "ar",
      segmentsCount: segments.length,
      chars: v.text.length,
      fetchedAt: new Date().toISOString(),
      error: ""
    });
    store.clearVideoSegments(v.id);
    store.addSegments(
      v.id,
      segments.map((s) => ({ ...s, norm: normalizeArabic(s.text) }))
    );
    videos++;
    chunks += segments.length;
  }
  let docs = 0;
  for (const d of DEMO_DOCS) {
    store.addDoc({ ...d, kind: "demo" });
    docs++;
  }
  store.setMeta("demoSeededAt", new Date().toISOString());
  return { videos, chunks, docs };
}

module.exports = { DEMO_VIDEOS, DEMO_DOCS, seedDemo, segmentsFromText };
