/** يحوّل نصًا إلى مقاطع زمنية تقديرية (كل ~60 ثانية مقطع) */
function segmentsFromText(text, msPerChunk = 65000) {
  const parts = String(text)
    .split(/\n+/)
    .map((s) => s.trim())
    .filter(Boolean);
  let t = 0;
  const out = [];
  for (let i = 0; i < parts.length; i++) {
    out.push({
      idx: i,
      startMs: t,
      endMs: t + msPerChunk,
      text: parts[i]
    });
    t += msPerChunk;
  }
  return out;
}

