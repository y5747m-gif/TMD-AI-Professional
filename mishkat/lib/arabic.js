/* ==============================================================
 *  1) تطبيع النص العربي
 * ============================================================== */

const TASHKEEL_RE = /[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g;

function normalizeArabic(input) {
  let s = String(input == null ? "" : input);

  // إزالة التشكيل والتطويل
  s = s.replace(TASHKEEL_RE, "");

  // توحيد الهمزات والألفات
  s = s.replace(/[أإآٱﺃﺇﺁ]/g, "ا");
  s = s.replace(/[ىئي]/g, "ي").replace(/ئ/g, "ي");
  s = s.replace(/ؤ/g, "و");
  s = s.replace(/ة/g, "ه");

  // حروف عربية ممدودة/خاصة
  s = s.replace(/[ک]/g, "ك").replace(/[ﻻﻷﻹ]/g, "لا");
  s = s.replace(/گ/g, "ك").replace(/چ/g, "ك").replace(/پ/g, "ب").replace(/ڤ/g, "ف");

  // الأرقام العربية والإيرانية إلى لاتينية
  s = s.replace(/[\u0660-\u0669]/g, (d) => String(d.charCodeAt(0) - 0x0660));
  s = s.replace(/[\u06F0-\u06F9]/g, (d) => String(d.charCodeAt(0) - 0x06f0));

  // إزالة العلامات والرموز (نُبقي الحروف والأرقام والمسافات)
  s = s.replace(/[^\u0621-\u064Aa-z0-9\s]/g, " ");

  // ضغط المسافات
  s = s.replace(/\s+/g, " ").trim();

  return s;
}

