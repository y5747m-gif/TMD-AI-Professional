/** ترتيب احتمالي لأكثر الفئات مطابقةً للسؤال */
function classifyQuery(text) {
  const norm = normalizeArabic(text);
  const tokens = new Set(contentTokens(text));
  const scored = [];

  for (const cat of CATEGORIES) {
    let score = 0;
    const hits = [];
    for (const term of cat.terms) {
      const t = normalizeArabic(term);
      if (norm.includes(t)) {
        score += t.includes(" ") ? 2.2 : 1.6;
        hits.push(term);
      } else if (tokens.has(t)) {
        score += 1.2;
        hits.push(term);
      }
    }
    if (score > 0) scored.push({ id: cat.id, label: cat.label, score, hits });
  }

  scored.sort((a, b) => b.score - a.score);
  return {
    primary: scored[0] || { id: "general", label: "سؤال عام", score: 0, hits: [] },
    all: scored.slice(0, 3)
  };
}

